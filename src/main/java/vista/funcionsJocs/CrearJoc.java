    /**
     * Carrega els gèneres, prepara els spinners i aplica els textos.
     */
    private void configurarFormulari() {
        DefaultComboBoxModel<String> modelGeneres = new DefaultComboBoxModel<>();
        for (Genere genere : Genere.values()) {
            modelGeneres.addElement(genere.getNom());
        }
        jComboBoxGenereJocCreat.setModel(modelGeneres);

        jSpinnerUnitatsPS5.setModel(new SpinnerNumberModel(0, 0, 999, 1));
        jSpinnerUnitatsXbox.setModel(new SpinnerNumberModel(0, 0, 999, 1));
        jSpinnerUnitatsPC.setModel(new SpinnerNumberModel(0, 0, 999, 1));
        jSpinnerUnitatsSwitch2.setModel(new SpinnerNumberModel(0, 0, 999, 1));

        actualitzarSpinner(jCheckBoxPS5, jSpinnerUnitatsPS5);
        actualitzarSpinner(jCheckBoxXBOX, jSpinnerUnitatsXbox);
        actualitzarSpinner(jCheckBoxPC, jSpinnerUnitatsPC);
        actualitzarSpinner(jCheckBoxSwitch2, jSpinnerUnitatsSwitch2);
        
        configurarEditorSpinner(
                jSpinnerUnitatsPS5,
                jSpinnerUnitatsXbox,
                jSpinnerUnitatsPC,
                jSpinnerUnitatsSwitch2
        );
        aplicarTextos();
    }

